  "ASSET_ID" VARCHAR2(64 BYTE) NOT NULL,
  "EVENT_TYPE_ID" VARCHAR2(64 BYTE) NOT NULL,
  "EVENT_MSG" VARCHAR2(2048 BYTE) NOT NULL,
  "REPO_MSG" VARCHAR2(2048 BYTE),
  "UNIQUE_CODE" VARCHAR2(255 BYTE) NOT NULL,
  "BASE_VALUE" VARCHAR2(255 BYTE),
  "COLLECT_VALUE" VARCHAR2(255 BYTE),
  "FLAG" VARCHAR2(255 BYTE),
  "MATCH_FLAG" VARCHAR2(255 BYTE),
  "EVENT_LEVEL" VARCHAR2(255 BYTE) NOT NULL,
  "REMARK" VARCHAR2(255 BYTE),
  "CREATE_TIME" DATE NOT NULL,
  "UPDATE_TIME" DATE NOT NULL
);
 
ALTER TABLE "ALARM_EVENT" ADD PRIMARY KEY ("ID");
 
COMMENT ON COLUMN "ALARM_EVENT"."ASSET_ID" IS '资产ID';
COMMENT ON COLUMN "ALARM_EVENT"."EVENT_TYPE_ID" IS '事件类型ID';
COMMENT ON COLUMN "ALARM_EVENT"."EVENT_MSG" IS '事件原始信息';
COMMENT ON COLUMN "ALARM_EVENT"."REPO_MSG" IS '事件翻译后的信息';
COMMENT ON COLUMN "ALARM_EVENT"."UNIQUE_CODE" IS '事件的标识';
COMMENT ON COLUMN "ALARM_EVENT"."BASE_VALUE" IS '基础值（阈值事件）';
COMMENT ON COLUMN "ALARM_EVENT"."COLLECT_VALUE" IS '采集值（阈值事件）';
COMMENT ON COLUMN "ALARM_EVENT"."FLAG" IS '一些告警的特殊设定值（如端口索引、进程名称等）';
COMMENT ON COLUMN "ALARM_EVENT"."MATCH_FLAG" IS '事件组合的时候判定是否需要匹配告警码';
COMMENT ON COLUMN "ALARM_EVENT"."EVENT_LEVEL" IS '事件性质：异常事件、恢复事件、通知事件';
COMMENT ON COLUMN "ALARM_EVENT"."REMARK" IS '备注';
COMMENT ON COLUMN "ALARM_EVENT"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "ALARM_EVENT"."UPDATE_TIME" IS '更新时间';
 
--事件告警规则配置表--
CREATE TABLE "ALARM_EVENT_GROUP" (
  "ID" VARCHAR2(64 BYTE) NOT NULL,
