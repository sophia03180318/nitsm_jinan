ALTER TABLE "ALARM_EVENT_GROUP" ADD PRIMARY KEY ("ID");
 
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."ALARM_TYPE" IS '告警类型：硬件告警、软件告警';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."EVENT_TYPE_IDS" IS '事件类型ID组合-分割';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."LEVLE" IS '告警级别';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."ALARM_MSG_TEMP" IS '告警模板';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."RECOVER_FLAG" IS '告警是否可恢复标识';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."LOGICAL_FLAG" IS '逻辑与或关系';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."CREATE_DATE" IS '创建时间';
COMMENT ON COLUMN "ALARM_EVENT_GROUP"."NAME" IS '告警组名称';
 
--事件告警关联表--
