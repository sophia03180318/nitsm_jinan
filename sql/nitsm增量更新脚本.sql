  "EVENT_TYPE_IDS" VARCHAR2(1024 BYTE) NOT NULL,
  "LEVLE" NUMBER(2,0) NOT NULL,
  "ALARM_MSG_TEMP" VARCHAR2(255 BYTE) NOT NULL,
  "RECOVER_FLAG" NUMBER(2,0) NOT NULL,
  "LOGICAL_FLAG" NUMBER(2,0) NOT NULL,
  "CREATE_DATE" DATE NOT NULL
